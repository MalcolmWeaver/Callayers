const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(process.argv[2],'utf8').split('documents[0]=')[0];
let now=0,paint;
const elements={};for(const id of ['name','score','time','toggle','add','reset','resetTime'])elements[id]={value:id==='name'?'Your ideas':'',textContent:'',blur(){}};
const context={window:{},document:{getElementById:id=>elements[id]},performance:{now:()=>now},setInterval:fn=>{paint=fn;}};
vm.createContext(context);vm.runInContext(source+'\ninteractiveCard();',context);
elements.add.onclick();elements.add.onclick();assert.equal(elements.score.textContent,'2');
elements.name.value='Saved name';elements.toggle.onclick();now=12300;paint();
assert.equal(elements.time.textContent,'4:48');
const saved=context.window.CallayersCard.snapshot();assert.equal(saved.count,2);assert.equal(saved.title,'Saved name');
context.window.CallayersCard.restore(saved);now+=30000;paint();
assert.equal(context.window.CallayersCard.isRunning(),false);
assert.equal(elements.time.textContent,'4:48');assert.equal(elements.toggle.textContent,'Start');
elements.toggle.onclick();now+=2300;paint();assert.equal(elements.time.textContent,'4:46');
assert.equal(context.window.CallayersCard.isRunning(),true);
elements.toggle.onclick();const paused=context.window.CallayersCard.snapshot().remaining;now+=5000;assert.equal(context.window.CallayersCard.snapshot().remaining,paused);
elements.reset.onclick();assert.equal(elements.score.textContent,'0');
elements.resetTime.onclick();assert.equal(elements.time.textContent,'5:00');
console.log('Card controls, timer, saved values and paused restore passed');

const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync(process.argv[2],'utf8');
const script=html.split('<script>')[1].split('</script>')[0];
const listeners={},frames=[];
const text={style:{},value:'',scrollTop:0,scrollLeft:0,focus(){},setSelectionRange(){},addEventListener(type,handler){listeners[type]=handler;}};
const measure={style:{},textContent:''};
Object.defineProperty(measure,'scrollHeight',{get(){return Math.ceil(measure.textContent.split('\n').length*parseFloat(measure.style.fontSize)*1.2);}});
const elements={text,measure,surface:{style:{}},outline:{style:{}},handle:{style:{}}};
const context={document:{getElementById:id=>elements[id]},window:{},requestAnimationFrame:callback=>frames.push(callback)};
vm.runInNewContext(script,context);
const state=()=>context.window.textEditState;
context.window.beginTextEdit({text:'Test-',font:36,color:'#ff0000',width:480,scale:.5,dpi:1,inset:6});
const originalHeight=state().height;
text.value='Test-\n';text.scrollTop=30;
listeners.input();
assert.equal(state().text,'Test-\n');
assert(state().height>originalHeight,'Enter must report the empty next line before another character');
assert.equal(text.scrollTop,0);
assert.equal(text.style.fontSize,'36px');
assert.equal(text.style.color,'#ff0000');
assert.equal(text.style.width,'480px');
assert.notEqual(text.style.height,'1px','The focused editor must not collapse while measuring');
const newlineHeight=state().height;
while(frames.length)frames.shift()();
listeners.keyup({key:'Enter'});
assert.equal(state().height,newlineHeight);
let prevented=false;
listeners.keydown({key:'Escape',preventDefault(){prevented=true;}});
assert(prevented);
assert.equal(state().finish,'cancel');
state().finish='';
listeners.keydown({key:'Escape',isComposing:true,preventDefault(){throw Error('Composition must handle Escape itself');}});
assert.equal(state().finish,'');
listeners.keydown({key:'Enter',ctrlKey:true,preventDefault(){}});
assert.equal(state().finish,'commit');
console.log('Trailing newline, editor geometry, and cancellation checks passed. Browser rendering remains a user check.');
